#!/usr/bin/env python3
"""Embed a binary file as a static uint8_t array in a C header."""
import argparse
from pathlib import Path


def emit(input_path: Path, output_path: Path, symbol: str) -> None:
    data = input_path.read_bytes()
    if not symbol.isidentifier():
        raise ValueError("symbol must be a valid C identifier")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="ascii", newline="\n") as stream:
        stream.write("/* Generated by tools/bin2c.py; do not edit by hand. */\n")
        stream.write("#ifndef GENERATED_NOVEL_PLAYER_TEMPLATE_H\n")
        stream.write("#define GENERATED_NOVEL_PLAYER_TEMPLATE_H\n")
        stream.write("#include <stdint.h>\n")
        stream.write(f"static const uint8_t {symbol}[] = {{\n")
        for offset in range(0, len(data), 12):
            chunk = data[offset:offset + 12]
            stream.write("    " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",\n")
        stream.write("};\n")
        stream.write(f"#define {symbol.upper()}_SIZE ((uint32_t)sizeof({symbol}))\n")
        stream.write("#endif\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--symbol", default="vn_player_template")
    args = parser.parse_args()
    emit(args.input, args.output, args.symbol)
    print(f"[BIN2C] Embedded {args.input} -> {args.output} ({args.input.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
